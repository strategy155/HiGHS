"""Parse HiGHS/HiPO benchmark result files.

Extracts structured data from .out files generated by benchmark_hipo.sh.

Usage:
    uv run parse_results.py <results_dir> [--output results.parquet]
"""

import argparse
import sys
from pathlib import Path
from typing import Callable, Literal, TypeAlias, TypedDict

import polars as pl
from lark import Lark, Token, Transformer
from lark.exceptions import UnexpectedInput

# Output format
DEFAULT_OUTPUT_FILE = Path("results.parquet")

# File patterns
OUT_FILE_GLOB = "*.out"
FILENAME_SUFFIX = ".mps.out"
CONFIG_SEPARATOR = "-"
PROBLEM_SEPARATOR = "_"
THREADS_PREFIX = "t"

# Expected number of config parts: system-solver-parallel-tN
EXPECTED_CONFIG_PARTS = 4

# Parallel flag values
PARALLEL_ON = "paron"
PARALLEL_OFF = "paroff"

# Key-value separator in log lines
KEY_VALUE_SEPARATOR = ":"

# Lark grammar for parsing "key: value" lines from HiGHS output.
# Reference: https://lark-parser.readthedocs.io/en/latest/grammar.html
#
# Grammar rules:
#   start    - Entry point: expects KEY, separator, and optional VALUE
#   KEY      - Everything before the colon (may include spaces in key name)
#   _COLON   - The separator character (underscore prefix = filtered from tree)
#   VALUE    - Everything after the colon (whitespace stripped in transformer)
#
# Example inputs:
#   "HiPO runtime:                   20.15"  -> KEY="HiPO runtime", VALUE="20.15"
#   "Model status        : Optimal"         -> KEY="Model status", VALUE="Optimal"
KEY_VALUE_GRAMMAR = r"""
    start: KEY _COLON VALUE?

    KEY: /[^:\n]+/
    _COLON: ":"
    VALUE: /[^\n]+/
"""

GRAMMAR_START_RULE = "start"

# Default value when VALUE terminal is not present in parse result
EMPTY_VALUE = ""


class KeyValueTransformer(Transformer):
    """Transform Lark parse tree into (key, value) tuple with stripped whitespace.

    Reference: https://lark-parser.readthedocs.io/en/stable/json_tutorial.html

    Terminal methods receive lark.Token directly (Token subclasses str).
    Rule methods receive a list of transformed children.
    """

    def KEY(self, token: Token) -> str:
        """Strip whitespace from key token."""
        return token.strip()

    def VALUE(self, token: Token) -> str:
        """Strip whitespace from value token."""
        return token.strip()

    def start(self, items: list) -> tuple[str, str]:
        """Extract key and value from parsed items.

        Args:
            items: List containing [key] or [key, value].
                   COLON terminal is not included (filtered by Lark).

        Returns:
            Tuple of (key, value).
        """
        match items:
            case [key]:
                return (key, EMPTY_VALUE)
            case [key, value]:
                return (key, value)
            case _:
                raise ValueError(f"Unexpected parse result: {items}")


# Parser instance (created once, reused for performance)
_key_value_parser = Lark(KEY_VALUE_GRAMMAR, start=GRAMMAR_START_RULE)
_key_value_transformer = KeyValueTransformer()


# Type alias for metric extractor: (output_field_name, value_converter)
ValueConverter: TypeAlias = Callable[[str], int | float | str]

# Literal type for all valid ContentInfo field names.
# This enables type-safe dynamic key access to ContentInfo dict.
ContentInfoKey: TypeAlias = Literal[
    "hipo_runtime",
    "hipo_iterations",
    "ipx_iterations",
    "hipo_status",
    "model_status",
    "simplex_iterations",
    "ipm_iterations",
    "crossover_iterations",
    "objective_value",
    "highs_runtime",
]

MetricExtractor: TypeAlias = tuple[ContentInfoKey, ValueConverter]

# Metric key prefixes found in HiGHS output logs.
# These are the exact strings that appear before ":" in the log file.
METRIC_KEY_HIPO_RUNTIME = "HiPO runtime"
METRIC_KEY_HIPO_ITERATIONS = "HiPO iterations"
METRIC_KEY_IPX_ITERATIONS = "IPX iterations"
METRIC_KEY_STATUS = "Status"
METRIC_KEY_MODEL_STATUS = "Model status"
METRIC_KEY_SIMPLEX_ITERATIONS = "Simplex   iterations"  # Note: extra spaces in key
METRIC_KEY_IPM_ITERATIONS = "IPM       iterations"  # Note: extra spaces in key
METRIC_KEY_CROSSOVER_ITERATIONS = "Crossover iterations"
METRIC_KEY_OBJECTIVE_VALUE = "Objective value"
METRIC_KEY_HIGHS_RUNTIME = "HiGHS run time"

# Output field names for FilenameInfo dict
FIELD_SYSTEM = "system"
FIELD_SOLVER = "solver"
FIELD_IS_PARALLEL = "is_parallel"
FIELD_THREADS = "threads"
FIELD_PROBLEM = "problem"

# Column order for sorting output DataFrame
SORT_COLUMNS = [FIELD_PROBLEM, FIELD_SYSTEM, FIELD_SOLVER, FIELD_IS_PARALLEL, FIELD_THREADS]

# Output field names for ContentInfo dict
FIELD_HIPO_RUNTIME = "hipo_runtime"
FIELD_HIPO_ITERATIONS = "hipo_iterations"
FIELD_IPX_ITERATIONS = "ipx_iterations"
FIELD_HIPO_STATUS = "hipo_status"
FIELD_MODEL_STATUS = "model_status"
FIELD_SIMPLEX_ITERATIONS = "simplex_iterations"
FIELD_IPM_ITERATIONS = "ipm_iterations"
FIELD_CROSSOVER_ITERATIONS = "crossover_iterations"
FIELD_OBJECTIVE_VALUE = "objective_value"
FIELD_HIGHS_RUNTIME = "highs_runtime"

# Configuration for extracting metrics from parsed key-value lines.
# Maps: key_prefix → (output_field_name, type_converter)
#
# The key_prefix is matched against the start of parsed keys.
# The type_converter converts the string value to the appropriate type.
METRIC_EXTRACTORS: dict[str, MetricExtractor] = {
    METRIC_KEY_HIPO_RUNTIME: (FIELD_HIPO_RUNTIME, float),
    METRIC_KEY_HIPO_ITERATIONS: (FIELD_HIPO_ITERATIONS, int),
    METRIC_KEY_IPX_ITERATIONS: (FIELD_IPX_ITERATIONS, int),
    METRIC_KEY_STATUS: (FIELD_HIPO_STATUS, str),
    METRIC_KEY_MODEL_STATUS: (FIELD_MODEL_STATUS, str),
    METRIC_KEY_SIMPLEX_ITERATIONS: (FIELD_SIMPLEX_ITERATIONS, int),
    METRIC_KEY_IPM_ITERATIONS: (FIELD_IPM_ITERATIONS, int),
    METRIC_KEY_CROSSOVER_ITERATIONS: (FIELD_CROSSOVER_ITERATIONS, int),
    METRIC_KEY_OBJECTIVE_VALUE: (FIELD_OBJECTIVE_VALUE, float),
    METRIC_KEY_HIGHS_RUNTIME: (FIELD_HIGHS_RUNTIME, float),
}


class ContentInfo(TypedDict, total=False):
    """Parsed metrics from benchmark output content.

    All fields are optional (total=False) since not all metrics
    may be present in every output file.
    """

    hipo_runtime: float
    hipo_iterations: int
    ipx_iterations: int
    hipo_status: str
    model_status: str
    simplex_iterations: int
    ipm_iterations: int
    crossover_iterations: int
    objective_value: float
    highs_runtime: float


def parse_key_value_line(line: str) -> tuple[str, str] | None:
    """Parse a single key:value line using the Lark parser.

    Args:
        line: Line potentially containing "key: value" format.

    Returns:
        Tuple of (key, value) with whitespace stripped, or None if line
        doesn't contain the separator or fails to parse.
    """
    if KEY_VALUE_SEPARATOR not in line:
        return None

    try:
        tree = _key_value_parser.parse(line)
        return _key_value_transformer.transform(tree)
    except UnexpectedInput:
        # Line doesn't match key:value grammar
        return None


def find_extractor_for_key(key: str) -> MetricExtractor | None:
    """Find the single extractor matching the given key prefix.

    Each key should match at most one extractor. The first matching
    extractor (by prefix) is returned.

    Args:
        key: Parsed key from log line.

    Returns:
        Matching extractor tuple, or None if key matches no extractor.
    """
    for key_prefix, extractor in METRIC_EXTRACTORS.items():
        if key.startswith(key_prefix):
            return extractor
    return None


def extract_metric(key: str, value: str, result: ContentInfo) -> None:
    """Extract a metric if key matches known patterns.

    Updates result dict in place with converted value.

    Args:
        key: Parsed key from log line.
        value: Parsed value string.
        result: ContentInfo dict to update.

    Raises:
        ValueError: If value cannot be converted to expected type.
    """
    extractor = find_extractor_for_key(key)
    if extractor is not None:
        field_name, converter = extractor
        result[field_name] = converter(value)


def parse_content(content: str) -> ContentInfo:
    """Extract metrics from benchmark output content.

    Parses each line looking for key:value pairs matching known metrics,
    then converts values to appropriate types.

    Args:
        content: Full text content of the .out file.

    Returns:
        Dictionary with extracted and typed metrics.

    Raises:
        ValueError: If a matched metric value cannot be converted.
    """
    result: ContentInfo = {}

    # Parse all lines, filter out failed parses
    parsed_lines = [
        parsed
        for line in content.splitlines()
        if (parsed := parse_key_value_line(line)) is not None
    ]

    for key, value in parsed_lines:
        extract_metric(key, value, result)

    return result


class FilenameInfo(TypedDict):
    """Parsed benchmark configuration from filename."""

    system: str
    solver: str
    is_parallel: bool
    threads: int
    problem: str


def parse_config_str(config_str: str) -> tuple[str, str, bool, int]:
    """Parse configuration string into components.

    Args:
        config_str: Configuration string like 'augmented-highs-paron-t256'.

    Returns:
        Tuple of (system, solver, is_parallel, threads).

    Raises:
        ValueError: If config_str doesn't match expected pattern.
    """
    config_parts = config_str.split(CONFIG_SEPARATOR)

    if len(config_parts) != EXPECTED_CONFIG_PARTS:
        raise ValueError(
            f"Expected {EXPECTED_CONFIG_PARTS} config parts, got {len(config_parts)}: {config_str}"
        )

    system, solver, parallel_str, threads_str = config_parts

    if parallel_str == PARALLEL_ON:
        is_parallel = True
    elif parallel_str == PARALLEL_OFF:
        is_parallel = False
    else:
        raise ValueError(
            f"Invalid parallel value '{parallel_str}', expected '{PARALLEL_ON}' or '{PARALLEL_OFF}'"
        )

    if not threads_str.startswith(THREADS_PREFIX):
        raise ValueError(
            f"Threads field must start with '{THREADS_PREFIX}': {threads_str}"
        )

    threads_value = threads_str.removeprefix(THREADS_PREFIX)
    try:
        threads = int(threads_value)
    except ValueError as e:
        raise ValueError(f"Invalid threads value '{threads_value}': {e}") from e

    return system, solver, is_parallel, threads


def parse_filename(filename: str) -> FilenameInfo:
    """Parse benchmark configuration from filename.

    Pattern: {system}-{solver}-{parallel}-t{threads}_{problem}.mps.out

    Args:
        filename: Name of the .out file.

    Returns:
        Parsed configuration.

    Raises:
        ValueError: If filename doesn't match expected pattern.
    """
    if not filename.endswith(FILENAME_SUFFIX):
        raise ValueError(f"Filename must end with '{FILENAME_SUFFIX}': {filename}")

    base = filename.removesuffix(FILENAME_SUFFIX)

    if PROBLEM_SEPARATOR not in base:
        raise ValueError(
            f"Filename must contain '{PROBLEM_SEPARATOR}' separator: {filename}"
        )

    config_str, problem = base.split(PROBLEM_SEPARATOR, maxsplit=1)

    system, solver, is_parallel, threads = parse_config_str(config_str)

    return {
        FIELD_SYSTEM: system,
        FIELD_SOLVER: solver,
        FIELD_IS_PARALLEL: is_parallel,
        FIELD_THREADS: threads,
        FIELD_PROBLEM: problem,
    }


class BenchmarkResult(TypedDict, total=False):
    """Combined result from filename and content parsing."""

    # From filename
    system: str
    solver: str
    is_parallel: bool
    threads: int
    problem: str
    # From content
    hipo_runtime: float
    hipo_iterations: int
    ipx_iterations: int
    hipo_status: str
    model_status: str
    simplex_iterations: int
    ipm_iterations: int
    crossover_iterations: int
    objective_value: float
    highs_runtime: float


def parse_file(filepath: Path) -> BenchmarkResult:
    """Parse a single benchmark result file.

    Extracts configuration from filename and metrics from content.

    Args:
        filepath: Path to the .out file.

    Returns:
        Combined benchmark result.

    Raises:
        ValueError: If filename or content parsing fails.
    """
    filename_info = parse_filename(filepath.name)
    content = filepath.read_text(encoding="utf-8")
    content_info = parse_content(content)

    return BenchmarkResult(**filename_info, **content_info)


def main() -> int:
    """Parse benchmark results and save to parquet.

    Returns:
        Exit code (0 for success, 1 for error).
    """
    parser = argparse.ArgumentParser(
        description="Parse HiGHS/HiPO benchmark result files"
    )
    parser.add_argument(
        "results_dir",
        type=Path,
        help="Directory containing .out files",
    )
    parser.add_argument(
        "--output",
        "-o",
        type=Path,
        default=DEFAULT_OUTPUT_FILE,
        help=f"Output file path (default: {DEFAULT_OUTPUT_FILE})",
    )

    args = parser.parse_args()

    if not args.results_dir.is_dir():
        print(f"Error: {args.results_dir} is not a directory", file=sys.stderr)
        return 1

    out_files = list(args.results_dir.glob(OUT_FILE_GLOB))
    print(f"Found {len(out_files)} .out files")

    if not out_files:
        print("No .out files found", file=sys.stderr)
        return 1

    # Parse all files - fails on first error
    results = [parse_file(filepath) for filepath in out_files]
    print(f"Parsed {len(results)} files")

    # Create and sort DataFrame
    df = pl.DataFrame(results)
    df = df.sort(SORT_COLUMNS)

    # Save to parquet
    df.write_parquet(args.output)
    print(f"Saved to {args.output}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
